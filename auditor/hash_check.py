"""Стъпка 5: Проверка за липсваща проверка на целостта (хешове).

Хешът е като "пръстов отпечатък" на файла - уникален код, изчислен от
съдържанието му. Ако в requirements.txt е записан очакваният хеш,
pip може да провери при инсталиране дали изтегленият файл съвпада точно
с него. Без хешове няма гаранция, че файлът не е бил подменен по пътя
(например компрометиран сървър или кеш).

Тази проверка е само информативна - липсата на хеш не е толкова
сериозен проблем, колкото известна уязвимост, но е добра практика.
"""


def find_missing_hashes(requirements):
    """Връща находки за библиотеки, чийто ред в requirements.txt
    НЕ съдържа --hash=... стойност."""
    findings = []
    for req in requirements:
        if not req.hashes:
            findings.append({
                "name": req.name,
                "line_number": req.line_number,
            })
    return findings
